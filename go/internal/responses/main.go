// Command responses writes responses.gen.go: a Raw method on each of the
// client's answers, which oapi-codegen gives a Body field and no method to
// reach it by, so that runyard.Response is one interface every answer is
// and a caller can say what went wrong with any of them in one place.
//
//	go run ./internal/responses client.gen.go responses.gen.go
//
// `make generate` runs it after oapi-codegen, from sdk/go.
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io"
	"os"
	"strings"
)

func main() { os.Exit(run(os.Args[1:], os.Stderr)) }

// run is the command, and its exit status.
func run(args []string, stderr io.Writer) int {
	if err := write(args); err != nil {
		_, _ = fmt.Fprintln(stderr, "responses:", err)
		return 1
	}
	return 0
}

func write(args []string) error {
	if len(args) != 2 {
		return errors.New("usage: responses <client.gen.go> <responses.gen.go>")
	}
	src, err := os.ReadFile(args[0]) //nolint:gosec // the file make generate names, as anybody running it does
	if err != nil {
		return err
	}
	out, err := generate(src)
	if err != nil {
		return err
	}
	return os.WriteFile(args[1], out, 0o644) //nolint:gosec // source code, read by anybody
}

// generate is the file of Raw methods for the answers declared in src, in the
// order src declares them.
func generate(src []byte) ([]byte, error) {
	file, err := parser.ParseFile(token.NewFileSet(), "client.gen.go", src, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/responses from client.gen.go. DO NOT EDIT.\n\npackage %s\n", file.Name.Name)
	n := 0
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || !answer(ts) {
				continue
			}
			fmt.Fprintf(&b, "\n// Raw is the body the answer was read from.\nfunc (r *%s) Raw() []byte { return r.Body }\n", ts.Name.Name)
			n++
		}
	}
	if n == 0 {
		return nil, errors.New("no answer of the client's in the file")
	}
	return format.Source(b.Bytes())
}

// answer is whether ts is one of ClientWithResponses' answers: a struct named
// …Response with the body it was read from, Body []byte, and HTTPResponse.
func answer(ts *ast.TypeSpec) bool {
	st, ok := ts.Type.(*ast.StructType)
	if !ok || !strings.HasSuffix(ts.Name.Name, "Response") {
		return false
	}
	var body, http bool
	for _, field := range st.Fields.List {
		for _, name := range field.Names {
			switch name.Name {
			case "Body":
				body = isBytes(field.Type)
			case "HTTPResponse":
				http = true
			}
		}
	}
	return body && http
}

func isBytes(e ast.Expr) bool {
	arr, ok := e.(*ast.ArrayType)
	if !ok || arr.Len != nil {
		return false
	}
	elt, ok := arr.Elt.(*ast.Ident)
	return ok && elt.Name == "byte"
}
