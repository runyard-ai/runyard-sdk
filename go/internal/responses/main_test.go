package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"go.uber.org/goleak"
)

func TestMain(m *testing.M) { goleak.VerifyTestMain(m) }

const answers = `package agents

import "net/http"

type GetThingResponse struct {
	Body         []byte
	HTTPResponse *http.Response
	JSON200      *Thing
}

// Not an answer: no HTTPResponse.
type ThingResponse struct {
	Body []byte
}

// Not one either: its Body is not the bytes read.
type OtherResponse struct {
	Body         [4]byte
	HTTPResponse *http.Response
}

type StrangeResponse struct {
	Body         string
	HTTPResponse *http.Response
}

type ListThingsResponse struct {
	Body, Spare  []byte
	HTTPResponse *http.Response
}

type Response = GetThingResponse

type Thing struct{ Body []byte }

func (r GetThingResponse) StatusCode() int { return 0 }

var x = 1
`

func TestGenerate(t *testing.T) {
	got, err := generate([]byte(answers))
	if err != nil {
		t.Fatal(err)
	}
	want := `// Code generated by internal/responses from client.gen.go. DO NOT EDIT.

package agents

// Raw is the body the answer was read from.
func (r *GetThingResponse) Raw() []byte { return r.Body }

// Raw is the body the answer was read from.
func (r *ListThingsResponse) Raw() []byte { return r.Body }
`
	if string(got) != want {
		t.Errorf("got\n%s\nwant\n%s", got, want)
	}

	for name, src := range map[string]string{
		"not Go":       "package",
		"no answer":    "package agents\n\ntype Thing struct{}\n",
		"empty":        "",
		"only answers": "package agents\n\ntype GetResponse struct{ Body [][]byte; HTTPResponse int }\n",
	} {
		if out, err := generate([]byte(src)); err == nil {
			t.Errorf("%s: %s", name, out)
		}
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	in, out := filepath.Join(dir, "agents.gen.go"), filepath.Join(dir, "responses.gen.go")
	if err := os.WriteFile(in, []byte(answers), 0o600); err != nil {
		t.Fatal(err)
	}
	var stderr bytes.Buffer
	if status := run([]string{in, out}, &stderr); status != 0 || stderr.Len() != 0 {
		t.Fatalf("%d %s", status, &stderr)
	}
	if written, err := os.ReadFile(out); err != nil || !bytes.Contains(written, []byte("func (r *GetThingResponse) Raw()")) {
		t.Fatalf("%s %v", written, err)
	}

	for name, args := range map[string][]string{
		"no arguments":     nil,
		"one":              {in},
		"three":            {in, out, out},
		"no such file":     {filepath.Join(dir, "missing.go"), out},
		"not Go":           {out + ".none", out},
		"nowhere to write": {in, filepath.Join(dir, "no", "such", "dir", "x.go")},
	} {
		if name == "not Go" {
			if err := os.WriteFile(args[0], []byte("package"), 0o600); err != nil {
				t.Fatal(err)
			}
		}
		stderr.Reset()
		if status := run(args, &stderr); status != 1 || !strings.HasPrefix(stderr.String(), "responses: ") {
			t.Errorf("%s: %d %q", name, status, &stderr)
		}
	}
}
